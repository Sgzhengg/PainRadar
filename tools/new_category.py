"""Scaffold a new category taxonomy, either from a template or via the LLM.

    python tools/new_category.py --name notes --product "笔记工具" --description "Notion/Obsidian 类"
    python tools/new_category.py --name pdf2 --product "PDF 工具" --from-template pdf

Writes var/pain_taxonomy_<name>.json and prints a ready-to-run deepdive command.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from painradar.deepdive import HttpClient, _chat  # noqa: E402

SCAFFOLD_SYSTEM = """你是产品研究助理。给定一个产品品类，生成专项挖掘所需的骨架。返回 JSON：
{
 "themes": ["6-10 个中文主题，覆盖该品类常见痛点，最后一个固定为 其他"],
 "subreddits": ["2-4 个最相关的 Reddit 板块，不带 r/"],
 "keywords": ["5-8 个英文关键词，偏向痛点/流失/付费"],
 "domain_terms": ["3-6 个英文领域词，用于排除跨领域噪声"]
}
只返回 JSON。"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--name", required=True, help="slug，如 notes")
    ap.add_argument("--product", required=True)
    ap.add_argument("--description", default="")
    ap.add_argument("--from-template", default="")
    args = ap.parse_args()

    templates_path = ROOT / "var" / "category_templates.json"
    templates = json.loads(templates_path.read_text(encoding="utf-8"))["templates"]

    if args.from_template:
        template = templates.get(args.from_template)
        if not template:
            print(f"unknown template: {args.from_template}; available: {', '.join(templates)}")
            return 1
        data = {
            "name": args.name,
            "themes": template["themes"],
            "subreddits": template["subreddits"],
            "keywords": template["keywords"],
            "domain_terms": template["domain_terms"],
        }
        print(f"copied template '{args.from_template}'")
    else:
        client = HttpClient(user_agent="PainRadar/0.1", timeout=120, max_retries=1, rate_per_sec=1)
        import os

        result = _chat(
            client,
            os.environ.get("PAINRADAR_LLM_BASE_URL", "https://api.deepseek.com/v1"),
            os.environ.get("PAINRADAR_LLM_API_KEY", ""),
            os.environ.get("PAINRADAR_LLM_MODEL", "deepseek-chat"),
            SCAFFOLD_SYSTEM,
            {"product": args.product, "description": args.description},
        )
        themes = [str(x).strip() for x in (result.get("themes") or []) if str(x).strip()]
        if "其他" not in themes:
            themes.append("其他")
        def tokens(items):
            out = []
            for item in items:
                for part in str(item).replace("/", " ").split():
                    token = part.strip().lower()
                    if len(token) >= 3 and token not in out:
                        out.append(token)
            return out

        data = {
            "name": args.name,
            "themes": themes[:10],
            "subreddits": [str(x).strip().lstrip("r/") for x in (result.get("subreddits") or [])],
            "keywords": tokens(result.get("keywords") or [])[:8],
            "domain_terms": tokens(result.get("domain_terms") or [])[:6],
        }
        print("generated by model")

    taxonomy_path = ROOT / "var" / f"pain_taxonomy_{args.name}.json"
    taxonomy_path.write_text(
        json.dumps({"name": args.name, "themes": data["themes"]}, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )
    print(f"themes({len(data['themes'])}): {'、'.join(data['themes'])}")
    print(f"written {taxonomy_path}")
    print("\n建议命令：")
    print(
        f'  python tools/deepdive_run.py --product "{args.product}" --focus pain '
        f'--subreddits {",".join(data["subreddits"])} '
        f'--keywords {",".join(data["keywords"])} '
        f'--taxonomy {args.name} '
        f'--domain-terms {",".join(data["domain_terms"])} '
        f'--runs 2 --out docs/deepdive-reports/{args.name}.md'
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
